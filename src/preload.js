const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('spider', {
  analyze: (doc) => ipcRenderer.invoke('analyze', doc),
  openFile: (file) => ipcRenderer.invoke('open-file', webUtils.getPathForFile(file)),
  pickFile: () => ipcRenderer.invoke('pick-file'),
  analyzeClipboard: () => ipcRenderer.invoke('analyze-clipboard'),
  spiderTake: () => ipcRenderer.invoke('spider-take'),
  pinSelection: () => ipcRenderer.invoke('pin-selection'),
  ask: (doc, q) => ipcRenderer.invoke('ask', doc, q),
  transform: (mode, text) => ipcRenderer.invoke('transform', mode, text),
  compare: (a, b) => ipcRenderer.invoke('compare', a, b),
  addCalendar: (ev) => ipcRenderer.invoke('add-calendar', ev),
  onTransformProgress: (cb) => ipcRenderer.on('transform-progress', (_e, t) => cb(t)),
  regionDone: (r) => ipcRenderer.send('region-done', r),
  historyList: (q) => ipcRenderer.invoke('history-list', q),
  historyOpen: (id) => ipcRenderer.invoke('history-open', id),
  historyDelete: (id) => ipcRenderer.invoke('history-delete', id),
  mainMenu: () => ipcRenderer.send('main-menu'),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, a) => cb(a)),
  onShowNotebook: (cb) => ipcRenderer.on('show-notebook', () => cb()),
  setShortcut: (id, keys, label) => ipcRenderer.invoke('set-shortcut', id, keys, label),
  clipboardPreview: () => ipcRenderer.invoke('clipboard-preview'),
  popupClose: () => ipcRenderer.invoke('popup-close'),
  popupDetails: (doc, result, focus) => ipcRenderer.invoke('popup-details', doc, result, focus),
  onDropZone: (cb) => ipcRenderer.on('drop-zone', (_e, on) => cb(on)),
  onPopupDoc: (cb) => ipcRenderer.on('popup-doc', (_e, d) => cb(d)),
  shortcuts: () => ipcRenderer.invoke('shortcuts'),
  shortcutRecording: (on) => ipcRenderer.send('shortcut-recording', on),
  onShortcutFired: (cb) => ipcRenderer.on('shortcut-fired', (_e, id) => cb(id)),
  cocoonList: () => ipcRenderer.invoke('cocoon-list'),
  cocoonAddFiles: (files) => ipcRenderer.invoke('cocoon-add-files', files.map((f) => webUtils.getPathForFile(f))),
  cocoonAddText: (text) => ipcRenderer.invoke('cocoon-add-text', text),
  cocoonCopy: (id) => ipcRenderer.invoke('cocoon-copy', id),
  cocoonMenu: (id) => ipcRenderer.send('cocoon-menu', id),
  cocoonDrag: (id) => ipcRenderer.send('cocoon-drag', id),
  onCocoons: (cb) => ipcRenderer.on('cocoons', (_e, list) => cb(list)),
  onCocoonCopied: (cb) => ipcRenderer.on('cocoon-copied', (_e, id) => cb(id)),
  onRigTrick: (cb) => ipcRenderer.on('rig-trick', (_e, t) => cb(t)),
  onOverlayStart: (cb) => ipcRenderer.on('overlay-start', (_e, d) => cb(d)),
  overlayDone: () => ipcRenderer.send('overlay-done'),
  analyzeText: (text) => ipcRenderer.invoke('analyze-text', text),
  openSettings: () => ipcRenderer.invoke('open-settings'),
  openMain: () => ipcRenderer.invoke('open-main'),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: (s) => ipcRenderer.invoke('save-settings', s),
  ollamaModels: () => ipcRenderer.invoke('ollama-models'),
  modelStatus: () => ipcRenderer.invoke('model-status'),
  modelDownload: (key) => ipcRenderer.invoke('model-download', key),
  modelCancel: () => ipcRenderer.invoke('model-cancel'),
  onModelProgress: (cb) => ipcRenderer.on('model-progress', (_e, p) => cb(p)),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  bubbleMenu: () => ipcRenderer.send('bubble-menu'),
  rigHover: (inside) => ipcRenderer.send('rig-hover', inside),
  rigDragStart: (length) => ipcRenderer.send('rig-drag-start', length),
  rigDragEnd: () => ipcRenderer.invoke('rig-drag-end'),
  onRigDragging: (cb) => ipcRenderer.on('rig-dragging', (_e, d) => cb(d)),
  onRigInit: (cb) => ipcRenderer.on('rig-init', (_e, d) => cb(d)),
  onCursor: (cb) => ipcRenderer.on('cursor', (_e, p) => cb(p)),
  onThreadLength: (cb) => ipcRenderer.on('thread-length', (_e, l) => cb(l)),
  onBusy: (cb) => ipcRenderer.on('busy', (_e, b) => cb(b)),
  onDocument: (cb) => ipcRenderer.on('document', (_e, d) => cb(d)),
  closeWindow: () => ipcRenderer.invoke('hide-main'),
  onProgress: (cb) => ipcRenderer.on('progress', (_e, n) => cb(n)),
});
