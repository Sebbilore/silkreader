import { _electron as electron } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const app = await electron.launch({ executablePath: './node_modules/electron/dist/electron', args: ['--no-sandbox', '.'], env: { ...process.env, SPIDER_MOCK: 'test/mock.json', HOME: process.argv[2] } });
app.process().stderr.on('data', (d) => process.stdout.write('stderr: ' + String(d).slice(0, 300)));
await new Promise((r) => setTimeout(r, 3000));
const b = app.windows().find((w) => w.url().includes('bubble'));
console.log('clipboard:', JSON.stringify(await app.evaluate(({ clipboard }) => clipboard.readText())));
const r = await b.evaluate(() => window.spider.analyzeClipboard().then(() => 'ok', (e) => 'ERR ' + e.message));
console.log('invoke result:', r);
await new Promise((r) => setTimeout(r, 2000));
console.log('BrowserWindows:', await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().map((w) => [w.webContents.getURL().split('/').pop(), w.isVisible()])));
await app.close();
