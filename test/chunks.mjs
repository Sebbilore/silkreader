import { _electron as electron } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
const [home, model, reps] = [process.argv[2], process.argv[3], Number(process.argv[4] || 1)];
const app = await electron.launch({ executablePath: './node_modules/electron/dist/electron', args: ['--no-sandbox', '.'], env: { ...process.env, HOME: home, SILK_MODEL_PATH: model } });
await new Promise((r) => setTimeout(r, 3000));
const pop = app.windows().find((w) => w.url().includes('popup')) || await app.waitForEvent('window', { predicate: (w) => w.url().includes('popup'), timeout: 8000 }).catch(() => null);
const text = Array.from({ length: reps }, (_, i) => `Teil ${i + 1}.\n\n` + fs.readFileSync('test/sample.txt', 'utf8')).join('\n\n');
const t0 = Date.now();
const stages = new Set();
const page = pop || app.windows().find((w) => w.url().includes('bubble'));
page.on('console', () => {});
const res = await page.evaluate(async (t) => {
  const seen = [];
  window.spider.onProgress((p) => { if (p.stage?.stage && seen[seen.length - 1] !== p.stage.stage) seen.push(p.stage.stage); });
  const r = await window.spider.analyze({ title: 'Langer Bericht', source: 'text', pages: [t] });
  return { ok: r.ok, error: r.error, figures: r.result?.figures.length, summaryLen: r.result?.summary.length, seen };
}, text);
console.log(`Wörter: ${text.split(/\s+/).length} | Dauer: ${Math.round((Date.now() - t0) / 1000)} s | ok: ${res.ok} ${res.error || ''}`);
console.log('Schritte:', res.seen.join(' → '));
console.log('Angaben:', res.figures, '| Zusammenfassung Zeichen:', res.summaryLen);
await app.close();
