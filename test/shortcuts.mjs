import { _electron as electron } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const [out, home, folder] = process.argv.slice(2);
const app = await electron.launch({ executablePath: './node_modules/electron/dist/electron', args: ['--no-sandbox', '.'], env: { ...process.env, SPIDER_MOCK: 'test/mock.json', HOME: home, SILK_MODEL_PATH: '/nonexistent' } });
const errs = [];
app.on('window', (w) => w.on('pageerror', (e) => errs.push(String(e))));
await new Promise((r) => setTimeout(r, 3500));
const set = app.windows().find((w) => w.url().includes('settings'));
set.on('pageerror', (e) => errs.push(String(e)));
await set.waitForSelector('kbd.rec');
console.log('vorher:', await set.evaluate(() => [...document.querySelectorAll('kbd.rec')].map((k) => k.textContent).join(', ')));
await set.click('kbd.rec[data-id="take"]');
await set.keyboard.press('Control+Alt+J');
await new Promise((r) => setTimeout(r, 600));
console.log('nachher:', await set.evaluate(() => document.querySelector('kbd.rec[data-id="take"]').textContent), '| registriert:', await app.evaluate(({ globalShortcut }) => globalShortcut.isRegistered('CommandOrControl+Alt+J')));
const ud = await app.evaluate(({ app }) => app.getPath('userData'));
const fs = await import('fs');
console.log('gespeichert:', JSON.stringify(JSON.parse(fs.readFileSync(ud + '/settings.json', 'utf8')).shortcuts));
await set.screenshot({ path: `${out}/settings.png`, fullPage: true });
// Ordner festhalten → Symbol + Menü
const rig = app.windows().find((w) => w.url().includes('bubble'));
await app.evaluate(async ({ ipcMain }, f) => { await ipcMain._invokeHandlers.get('cocoon-add-files')({}, [f]); }, folder);
await new Promise((r) => setTimeout(r, 800));
console.log('Ordner im Netz:', await rig.evaluate(() => { const i = document.querySelector('.item'); return i && { name: i.querySelector('.nm').textContent, ext: !!i.querySelector('.ext'), icon: !!i.querySelector('.ic').style.backgroundImage || i.querySelector('.ic').textContent }; }));
console.log('Netz anklickbar:', await rig.evaluate(() => onWeb({ x: HOLD.cx - 20, y: HOLD.cy + 10 })));
console.log('errors:', errs);
await app.close().catch(() => {});
